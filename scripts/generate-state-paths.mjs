#!/usr/bin/env node
// One-shot script: read us-atlas topojson, project to Albers USA, emit
// per-state SVG path strings into a TypeScript module.
//
// Run: node scripts/generate-state-paths.mjs

import { readFileSync, writeFileSync } from "node:fs";
import { feature } from "topojson-client";
import { geoAlbersUsa, geoPath } from "d3-geo";

const TOPOJSON_PATH = "/tmp/us-states.json";
const OUTPUT_PATH = "app/tools/broker-decision-v2/_config/state-paths.ts";

// Map us-atlas FIPS codes to USPS 2-letter codes.
const FIPS_TO_CODE = {
  "01": "AL", "02": "AK", "04": "AZ", "05": "AR", "06": "CA", "08": "CO",
  "09": "CT", "10": "DE", "11": "DC", "12": "FL", "13": "GA", "15": "HI",
  "16": "ID", "17": "IL", "18": "IN", "19": "IA", "20": "KS", "21": "KY",
  "22": "LA", "23": "ME", "24": "MD", "25": "MA", "26": "MI", "27": "MN",
  "28": "MS", "29": "MO", "30": "MT", "31": "NE", "32": "NV", "33": "NH",
  "34": "NJ", "35": "NM", "36": "NY", "37": "NC", "38": "ND", "39": "OH",
  "40": "OK", "41": "OR", "42": "PA", "44": "RI", "45": "SC", "46": "SD",
  "47": "TN", "48": "TX", "49": "UT", "50": "VT", "51": "VA", "53": "WA",
  "54": "WV", "55": "WI", "56": "WY",
};

const VIEW_W = 800;
const VIEW_H = 500;

const topology = JSON.parse(readFileSync(TOPOJSON_PATH, "utf-8"));
const states = feature(topology, topology.objects.states);

const projection = geoAlbersUsa().fitSize([VIEW_W, VIEW_H], states);
const path = geoPath(projection);

const paths = {};
const centroids = {};
for (const f of states.features) {
  const code = FIPS_TO_CODE[f.id];
  if (!code) continue;
  const d = path(f);
  if (d) paths[code] = d;
  const c = path.centroid(f);
  if (Number.isFinite(c[0]) && Number.isFinite(c[1])) {
    centroids[code] = [Math.round(c[0] * 10) / 10, Math.round(c[1] * 10) / 10];
  }
}

const lines = [
  "// Auto-generated by scripts/generate-state-paths.mjs. Do not edit by hand.",
  "// Source: us-atlas states-10m.json (public domain).",
  "// Projection: d3-geo Albers USA, fit to 800 × 500 viewBox.",
  "",
  `export const STATE_MAP_VIEW_BOX = "0 0 ${VIEW_W} ${VIEW_H}";`,
  `export const STATE_MAP_WIDTH = ${VIEW_W};`,
  `export const STATE_MAP_HEIGHT = ${VIEW_H};`,
  "",
  "export const STATE_PATHS: Record<string, string> = {",
];
for (const [code, d] of Object.entries(paths)) {
  lines.push(`  ${code}: ${JSON.stringify(d)},`);
}
lines.push("};", "");
lines.push("export const STATE_CENTROIDS: Record<string, [number, number]> = {");
for (const [code, c] of Object.entries(centroids)) {
  lines.push(`  ${code}: [${c[0]}, ${c[1]}],`);
}
lines.push("};", "");

writeFileSync(OUTPUT_PATH, lines.join("\n"));
console.log(`Wrote ${Object.keys(paths).length} state paths to ${OUTPUT_PATH}`);
